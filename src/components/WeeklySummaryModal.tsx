"use client";
import { useState } from "react";
import type { WeeklySummaryReport } from "@/lib/types";

interface Props {
  report: WeeklySummaryReport;
  isOpen: boolean;
  onClose: () => void;
}

export default function WeeklySummaryModal({ report, isOpen, onClose }: Props) {
  const [sentNotification, setSentNotification] = useState(false);
  const [isSending, setIsSending] = useState(false);

  if (!isOpen) return null;

  const handleSendEmail = async () => {
    setIsSending(true);
    try {
      const res = await fetch("/api/reports/weekly", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ week_period: report.week_period }),
      });
      if (res.ok) {
        setSentNotification(true);
        setTimeout(() => setSentNotification(false), 3000);
      }
    } finally {
      setIsSending(false);
    }
  };

  return (
    <div className="wa-modal-overlay" onClick={onClose}>
      <div className="summary-modal-card animate-in" onClick={(e) => e.stopPropagation()}>
        {/* Header */}
        <div className="summary-modal-header">
          <div style={{ display: "flex", alignItems: "center", gap: "12px" }}>
            <div className="summary-icon-box">
              <svg width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.2" strokeLinecap="round" strokeLinejoin="round">
                <rect x="3" y="3" width="18" height="18" rx="2" />
                <line x1="8" y1="16" x2="8" y2="11" />
                <line x1="12" y1="16" x2="12" y2="8" />
                <line x1="16" y1="16" x2="16" y2="13" />
              </svg>
            </div>
            <div>
              <h2 style={{ fontSize: "18px", fontWeight: "700", margin: 0, color: "var(--text-primary)" }}>
                Weekly Quality Summary — Monday Briefing
              </h2>
              <p style={{ margin: "2px 0 0", fontSize: "12px", color: "var(--text-secondary)" }}>
                Period: {report.week_period} · Generated by <strong>Report Agent</strong> (MCP: Gmail &amp; Excel)
              </p>
            </div>
          </div>
          <button className="summary-close-btn" onClick={onClose} aria-label="Close">
            <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.5" strokeLinecap="round">
              <line x1="18" y1="6" x2="6" y2="18" />
              <line x1="6" y1="6" x2="18" y2="18" />
            </svg>
          </button>
        </div>

        {/* Big Highlights Banner */}
        <div className="summary-hero-stat">
          <div className="summary-hero-stat-badge">WEEKLY IMPACT</div>
          <div className="summary-hero-stat-main">
            &ldquo;We caught <strong>{report.mistakes_caught} mistakes</strong> last week, saving about <strong>{report.hours_saved} hours</strong>.&rdquo;
          </div>
          <div className="summary-hero-stat-sub">
            Estimated financial risk prevented: <strong>PKR {report.amount_protected_pkr.toLocaleString()}</strong> in ledger errors &amp; duplicate payouts.
          </div>
        </div>

        {/* Breakdown Grid */}
        <div className="summary-grid">
          <div className="summary-stat-box">
            <span className="summary-stat-number">{report.breakdown.arithmetic_errors}</span>
            <span className="summary-stat-label">Arithmetic Mismatches</span>
            <span className="summary-stat-desc">Qty × Price ≠ Total caught before save</span>
          </div>

          <div className="summary-stat-box">
            <span className="summary-stat-number">{report.breakdown.duplicate_bills}</span>
            <span className="summary-stat-label">Duplicate Bills Prevented</span>
            <span className="summary-stat-desc">Blocked double disbursement via DB check</span>
          </div>

          <div className="summary-stat-box">
            <span className="summary-stat-number">{report.breakdown.outlier_prices}</span>
            <span className="summary-stat-label">Price Outliers Flagged</span>
            <span className="summary-stat-desc">Statistical commodity benchmark alerts</span>
          </div>

          <div className="summary-stat-box">
            <span className="summary-stat-number">{report.breakdown.transpositions}</span>
            <span className="summary-stat-label">Digit Transpositions</span>
            <span className="summary-stat-desc">Invoice # typo matched with document</span>
          </div>
        </div>

        {/* Top Flagged Vendors */}
        <div className="summary-vendors-section">
          <h4 style={{ fontSize: "13px", margin: "0 0 10px", color: "var(--text-secondary)", textTransform: "uppercase", letterSpacing: "0.5px" }}>
            Top Vendors with Discrepancies Last Week
          </h4>
          <div style={{ display: "flex", gap: "10px", flexWrap: "wrap" }}>
            {report.top_flagged_vendors.map((v, idx) => (
              <div key={idx} className="vendor-pill">
                <span>{v.vendor}</span>
                <span className="vendor-pill-count">{v.count} mistakes</span>
              </div>
            ))}
          </div>
        </div>

        {/* Automation Meta Footer */}
        <div className="summary-automation-bar">
          <div style={{ fontSize: "12px", color: "var(--text-secondary)", display: "flex", alignItems: "center", gap: "6px" }}>
            <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round">
              <rect x="3" y="4" width="18" height="18" rx="2" />
              <line x1="16" y1="2" x2="16" y2="6" />
              <line x1="8" y1="2" x2="8" y2="6" />
              <line x1="3" y1="10" x2="21" y2="10" />
            </svg>
            <span><strong>Manager Agent:</strong> Automated schedule active via Calendar MCP (Mondays 09:00 AM PKT).</span>
          </div>
          <div style={{ display: "flex", gap: "8px" }}>
            <button className="btn btn--secondary btn--sm" onClick={handleSendEmail} disabled={isSending}>
              {isSending ? "Sending…" : sentNotification ? "Dispatched to Office Email" : "Send to Office via Gmail"}
            </button>
            <button className="btn btn--primary btn--sm" onClick={onClose}>
              Done
            </button>
          </div>
        </div>
      </div>
    </div>
  );
}
